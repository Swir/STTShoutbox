// No browser or server: exercise the actual frontend sound functions with a fake Audio.
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=await readFile(new URL('../Upload/jscripts/sttshoutbox.js',import.meta.url),'utf8');
const functions=source.split('// STT SOUND HELPERS START')[1].split('\n').slice(1).join('\n').split('// STT SOUND HELPERS END')[0];
const context=vm.createContext({URL});vm.runInContext(functions,context);
const {sttSoundKey:key,sttSoundPreferences:prefs,sttNewIncoming:incoming,sttSoundPlayer:player}=context;
let checks=0;const check=(value,label)=>{assert.ok(value,label);checks++;};
const memory=value=>({getItem:()=>value});
check(key('/forum/index.php?stt=1',7,'https://example.test/')==='stt_sound_v1:https://example.test/forum/index.php:7','Forum+UID key');
check(key('/forum/index.php?a=2',7,'https://example.test/')===key('/forum/index.php?a=3',7,'https://example.test/'),'Query/session changes retain preference');
check(key('/forum/index.php',7,'https://example.test/')!==key('/other/index.php',7,'https://example.test/'),'Different forum folders do not share preference');
check(key('/forum/index.php',7,'https://example.test/')!==key('/forum/index.php',8,'https://example.test/'),'Different users do not share preference');
check(prefs(null,'x',40).enabled===false&&prefs(null,'x',40).volume===40,'No storage keeps explicit opt-in');
check(prefs(memory('{broken'),'x',40).enabled===false,'Corrupt storage safe');
check(prefs(memory('{"enabled":true,"volume":75}'),'x',40).enabled===true&&prefs(memory('{"volume":75}'),'x',40).volume===75,'Saved preferences restored');
check(prefs(memory('{"enabled":"true","volume":"loud"}'),'x',40).enabled===false,'Do not accept invalid enabled value');
check(prefs(memory('{"volume":1000}'),'x',40).volume===100&&prefs(memory('{"volume":-1}'),'x',40).volume===0,'Volume clamped');
const row=(values={})=>({id:2,uid:8,deleted:false,event:null,...values});
check(!incoming([row()],0,false,7),'Initial history silent');
check(incoming([row({id:1})],0,true,7),'First new message after empty room sounds');
check(!incoming([row()],2,true,7),'Repeated poll silent');
check(!incoming([row({edited:4})],2,true,7),'Edit to existing row silent');
check(!incoming([row({id:1})],2,true,7),'Older history silent');
check(!incoming([row({uid:7})],1,true,7),'Own sent message silent');
check(!incoming([row({uid:0})],1,true,7),'Automatic bot response silent');
check(!incoming([row({event:{kind:'thread'}})],1,true,7),'Activity bot silent');
check(!incoming([row({deleted:true})],1,true,7),'Deleted message silent');
check(incoming([row({id:3,uid:7}),row()],1,true,7),'Incoming concurrent with own send still sounds');
check(!incoming([row()],0,false,7),'Switching conversation begins with silent history');
let audioCount=0,clock=0,fail=false,feedback=[];
class AudioFake{constructor(url){this.url=url;this.paused=true;audioCount++;}pause(){this.paused=true;}play(){if(fail)return Promise.reject(Error('blocked'));this.paused=false;return Promise.resolve();}}
const sound=player(AudioFake,'/notify.wav',value=>feedback.push(value),()=>clock);
check(!(await sound.play(40))&&audioCount===0,'No unsolicited autoplay or load before gesture');
check(await sound.play(40,true),'Preview initiates audible playback');
check(audioCount===1&&feedback.at(-1)===true,'One reusable Audio and success feedback');
check(!(await sound.play(40)),'Coalesce simultaneous new messages');
clock=3100;const notices=feedback.length;check(await sound.play(40),'New batch after cooldown');
check(feedback.length===notices,'Automatic chimes do not repeat settings status for screen readers');
check(audioCount===1,'Reuse player for every sound');
clock=6200;check(!(await sound.play(0)),'Zero volume skips notifications');
sound.stop();fail=true;check(!(await sound.play(40,true))&&feedback.at(-1)===false,'Blocked playback handled and reported');
fail=false;check(await sound.play(40,true),'Preview retries after failure');
const remembered=player(AudioFake,'/notify.wav',()=>{},()=>clock);
check(await remembered.unlock(),'Remembered setting unlocks silently after gesture');
check(await remembered.play(40),'Unlocked player allows later notification');
let resolvePlay;
class PendingAudio{pause(){}play(){return new Promise(resolve=>{resolvePlay=resolve;});}}
const interrupted=player(PendingAudio,'/notify.wav',()=>{});
const pending=interrupted.play(40,true);interrupted.stop();resolvePlay();check(!(await pending),'Turning off during play does not re-enable it');
const wav=await readFile(new URL('../Upload/jscripts/sttshoutbox/notify.wav',import.meta.url));
check(wav.toString('ascii',0,4)==='RIFF'&&wav.toString('ascii',8,12)==='WAVE','Bundled RIFF/WAVE asset');
check(wav.readUInt16LE(20)===1&&wav.readUInt16LE(22)===1&&wav.readUInt16LE(34)===16,'Universal PCM mono16 encoding');
check(wav.readUInt32LE(24)===44100&&wav.readUInt32LE(40)===wav.length-44,'Valid sample rate and data length');
let peak=0;for(let at=44;at<wav.length;at+=2)peak=Math.max(peak,Math.abs(wav.readInt16LE(at)));
check(peak>10000&&peak<20000,'Chime audible without clipping');
check(wav.readInt16LE(44)===0&&Math.abs(wav.readInt16LE(wav.length-2))<10,'Soft attack and ending avoid click');
console.log(JSON.stringify({status:'passed',checks,assetBytes:wav.length}));
